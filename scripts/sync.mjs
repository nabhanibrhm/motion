/* ------------------------------------------------------------------ SFX clips in scenes */

const sectionIds = new Set(voice.sections.map((s) => s.id));
for (const file of readdirSync(join(root, "compositions"))) {
  const id = file.replace(/\.html$/, "");
  if (!sectionIds.has(id)) continue;
  const rel = `compositions/${file}`;
  const S = F1.section(id);
  const D = F1.sceneFrames(id);
  const src = readFileSync(join(root, rel), "utf8");
  const out = src.replace(/<audio\b[^>]*\bdata-at="([^"]+)"[^>]*>/g, (tag, spec) => {
    const f = Math.max(0, Math.min(D - 1, Math.round(F1.at(S, spec))));
    const t = `${sec(f)}`;
    let next = /\bdata-start="[^"]*"/.test(tag) ? tag.replace(/\bdata-start="[^"]*"/, `data-start="${t}"`) : tag.replace(/<audio\b/, `<audio data-start="${t}"`);
    // SFX times are local to the scene: say so, so the linter never reads them as root-global timestamps.
    if (!/\bdata-hf-media-start-basis=/.test(next)) next = next.replace(/\bdata-start="/, 'data-hf-media-start-basis="local" data-start="');
    return next;
  });
  write(rel, out);
}

/* ------------------------------------------------------------------ report */

const rels = changed.map((c) => relative(root, join(root, c)));
if (checkOnly) {
  if (rels.length) {
    console.error(`sync: out of date: ${rels.join(", ")} (run npm run sync)`);
    process.exit(1);
  }
  console.log("sync: up to date");
} else {
  console.log(rels.length ? `sync: wrote ${rels.join(", ")}` : "sync: up to date");
  console.log(`sync: ${segments.filter((s) => s.kind === "section").length} sections, ${segments.filter((s) => s.kind === "chapter").length} chapter cards, ${sec(total)} s`);
}
