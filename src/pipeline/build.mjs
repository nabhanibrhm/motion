export function hyperframesPackage(repoRoot) {
  const path=createRequire(join(repoRoot,'package.json')).resolve('hyperframes/package.json');
  const pkg=JSON.parse(readFileSync(path,'utf8'));
  if(pkg.version!=='0.8.210') throw new Error(`Expected HyperFrames 0.8.210, found ${pkg.version}`);
  return {path,pkg,dir:dirname(path),bin:join(dirname(path),typeof pkg.bin==='string'?pkg.bin:pkg.bin.hyperframes)};
}
export const escapeHTML=s=>String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');

/** Composition HTML of one scene before SFX anchors are resolved: .html as authored, .js wrapped, otherwise a template. Shared with scripts/regress.mjs. */
export function compositionSource(ctx,scene,index) {
  if(!scene.file) return renderTemplate(scene,ctx,index);
  const text=readFileSync(within(ctx.episodeDir,scene.file),'utf8');
  return isWrappedScene(scene)?wrapScene(scene,index,text):text;
}

export async function buildEpisode(ctx,{check=false,locked=false}={}) {
  if(!locked&&!check) return withEpisodeLock(ctx,()=>buildEpisode(ctx,{check,locked:true}));
  if(check&&existsSync(join(ctx.repoRoot,'.cache/locks',ctx.id))) throw new Error(`Episode ${ctx.id} is busy; cannot check a changing build`);
  validateEpisode(ctx);
  const {manifest:voice}=await ensureVoice(ctx,{generate:false,checkOnly:check});
  validateEpisode(ctx,{voice});
  const warnings=[], F1=loadTiming(ctx,voice,{warnings}), timing=F1.segments();
  const {config:c,paths:p,repoRoot}=ctx, W=c.video.width,H=c.video.height,FPS=F1.FPS,RFPS=c.video.fps; // FPS = 30-fps timeline frame units; RFPS = render sampling rate (scenes get fractional f)
  const sec=f=>+(f/FPS).toFixed(4), changed=[], desired=new Map();
  const put=(path,text)=>desired.set(path,text);
  const kit=join(repoRoot,'src/runtime/f1');
  for(const name of readdirSync(kit)) if(name!=='voice.js') put(`lib/f1/${name}`,readFileSync(join(kit,name),'utf8'));
  put('lib/f1/voice.js',`// GENERATED by motion sync. Do not edit.\n(globalThis.F1 = globalThis.F1 || {}).VOICE = ${JSON.stringify(voice)};\nF1.CONFIG = ${JSON.stringify(runtimeConfig(c)).replace(/</g,'\\u003c')};\n`);
  put('compositions/background.html',readFileSync(join(repoRoot,'src/templates/background.html'),'utf8'));
  for(const [index,scene] of c.scenes.entries()) {
    const source=compositionSource(ctx,scene,index);
    const S=F1.section(scene.id),D=F1.sceneFrames(scene.id);
    const out=source.replace(/<audio\b[^>]*\bdata-at=(["'])(.*?)\1[^>]*>/g,(tag,_quote,spec)=>{
      let frame;
      try{frame=F1.at(S,spec);}catch(e){throw new Error(`${scene.id}: ${e.message}`);}
      if(!Number.isFinite(frame)) throw new Error(`${scene.id}: invalid SFX anchor ${spec}`);
      const t=sec(Math.max(0,Math.min(D-1,Math.round(frame))));
      let next=/\bdata-start=(["']).*?\1/.test(tag)?tag.replace(/\bdata-start=(["']).*?\1/,`data-start="${t}"`):tag.replace(/<audio\b/,`<audio data-start="${t}"`);
      if(!/\bdata-hf-media-start-basis=/.test(next)) next=next.replace(/\bdata-start="/,'data-hf-media-start-basis="local" data-start="');
      return next;
    });
    put(`compositions/${scene.id}.html`,out);
  }
  if(warnings.length) throw new Error(`Invalid anchors in ${ctx.id}:\n${warnings.join('\n')}`);
  const host=({id,src,start,dur,track,z,kind='graphics',vars})=>`    <div id="${id}" data-composition-id="${id}" data-composition-src="${src}"${vars?` data-variable-values='${escapeHTML(JSON.stringify(vars)).replace(/&quot;/g,'"').replace(/'/g,'&#39;')}'`:''} data-start="${start}" data-duration="${dur}" data-track-index="${track}" data-track-kind="${kind}" data-width="${W}" data-height="${H}" style="z-index: ${z}"></div>`;
  const sceneHosts=[],audio=[];
  for(const s of timing.list) {
    if(s.kind==='chapter') {
      const id=`chapter-${s.chapterIndex+1}`;
      put(`compositions/${id}.html`,titleCard(id,{title:s.chapter,frames:s.duration}));
      sceneHosts.push(host({id,src:`compositions/${id}.html`,start:sec(s.from),dur:sec(s.duration),track:1,z:1}));
    } else {
      const id=s.section.id;
      sceneHosts.push(host({id,src:`compositions/${id}.html`,start:sec(s.from),dur:sec(s.duration),track:1,z:1}));
      audio.push(`    <audio id="voice-${id}" src="public/${s.section.audio}" data-start="${sec(s.from)}" data-duration="${Math.floor(Math.min(sec(s.from+s.duration)-sec(s.from),s.section.duration)*1e4)/1e4}" data-track-index="10" data-volume="1"></audio>`);
    }
  }
  const libs=['voice','timing','core','mascot','toon','photo','words','bits','rig','world','cine'];
  // Opt-in look kit (src/templates/<look>-kit.js), loaded after cine; absent looks leave index.html unchanged.
  const look=c.runtime.look;
  if(look){put(`lib/f1/${look}.js`,readFileSync(join(repoRoot,'src/templates',`${look}-kit.js`),'utf8'));libs.push(look);}
  put('index.html',`<!doctype html>
<!-- GENERATED by motion sync. Do not edit. -->
<html lang="id"><head><meta charset="UTF-8" /><meta name="viewport" content="width=${W}, height=${H}" /><title>${escapeHTML(c.title)}</title>
<link rel="stylesheet" href="lib/f1/f1.css" />
<script src="lib/vendor/gsap.min.js"></script>
${libs.map(name=>`<script src="lib/f1/${name}.js"></script>`).join('\n')}
<style>*{margin:0;padding:0;box-sizing:border-box}html,body{width:${W}px;height:${H}px;overflow:hidden;background:var(--editorial-bg)}</style>
</head><body>
<div id="root" data-composition-id="${ctx.id}" data-start="0" data-duration="${sec(timing.total)}" data-fps="${RFPS}" data-width="${W}" data-height="${H}">
${host({id:'background',src:'compositions/background.html',start:0,dur:sec(timing.total),track:0,z:0})}
${sceneHosts.join('\n')}
${host({id:'captions',src:'compositions/captions.html',start:0,dur:sec(timing.total),track:3,z:100,kind:'captions'})}
${audio.join('\n')}
</div><script>window.__timelines["${ctx.id}"] = gsap.timeline({paused:true});</script></body></html>\n`);
  put('compositions/captions.html',captions({F1,segments:timing.list,width:W,height:H,profile:c.runtime.profile,look:c.runtime.look,palette:c.runtime.palette}));
  put('hyperframes.json',JSON.stringify({paths:{blocks:'compositions',components:'compositions/components',assets:'public'},media:{autoProxy:true}},null,2)+'\n');
  const hf=hyperframesPackage(repoRoot),gsap=join(hf.dir,'dist/vendor/npm/gsap@3.15.0/dist/gsap.min.js');
  if(!existsSync(gsap)) throw new Error('Pinned HyperFrames local GSAP 3.15.0 is missing; reinstall dependencies');
  put('lib/vendor/gsap.min.js',readFileSync(gsap,'utf8'));
  for(const [rel,text] of desired) {
    const path=within(p.buildDir,rel);
    if(existsSync(path)&&readFileSync(path,'utf8')===text) continue;
    changed.push(rel);
    if(!check){mkdirSync(dirname(path),{recursive:true});const tmp=`${path}.write-${process.pid}`;writeFileSync(tmp,text,'utf8');renameSync(tmp,path);}
  }
  // Reconcile only engine-managed generated files; imported/source paths are never removed.
  const managedPath=within(p.buildDir,'.motion-generated.json');
  const previous=existsSync(managedPath)?JSON.parse(readFileSync(managedPath,'utf8')):[];
  for(const rel of previous) if(!desired.has(rel)) {
    const path=within(p.buildDir,rel);changed.push(rel);
    if(!check&&existsSync(path)) unlinkSync(path);
  }
  if(!check) {
    const managedText=JSON.stringify([...desired.keys()],null,2)+'\n';
    if(!existsSync(managedPath)||readFileSync(managedPath,'utf8')!==managedText) {
      const tmp=`${managedPath}.write-${process.pid}`;
      writeFileSync(tmp,managedText);renameSync(tmp,managedPath);
    }
  }
  const assets=await stageAssets(ctx,{check});
  changed.push(...assets.changed.map(path=>`public/${path}`));
  if(check&&!assets.current) throw new Error(`Build assets out of date for ${ctx.id}; run sync`);
  if(check&&changed.length) throw new Error(`Build out of date for ${ctx.id}: ${changed.join(', ')}; run sync`);
  return {buildDir:p.buildDir,changed,timing:{...timing,fps:FPS,renderFps:RFPS,seconds:sec(timing.total)}};
}
