// Regenerates everything that is derived from the voice timing (src/data/rupiah-voice.json, written by
// voiceover/generate.py). Run it after re-generating the voice; `npm run dev|check|render` run it first.
//
//   lib/f1/voice.js            the voice data for the browser (F1.VOICE)
//   index.html                 root composition: one host per section, voice <audio>, captions (1080x1920)
//   compositions/captions.html every caption group as a timed clip (captions track)
//   compositions/<scene>.html  re-times SFX clips: an <audio data-at="word:tickets"> gets data-start from its anchor
//
// Hand-written files are never overwritten: scenes only get their SFX `data-start` values refreshed.
// Usage: node scripts/sync.mjs [--check]   (--check: exit 1 if anything would change, write nothing)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");
const voice = JSON.parse(readFileSync(join(root, "src/data/rupiah-voice.json"), "utf8"));

globalThis.F1 = { VOICE: voice };
await import(pathToFileURL(join(root, "lib/f1/timing.js")).href);
const F1 = globalThis.F1;
const FPS = F1.FPS;
// Vertical 9:16 short (TikTok / Shorts / Reels).
const W = 1080;
const H = 1920;

const { list: segments, total } = F1.segments();
const sec = (frames) => +(frames / FPS).toFixed(4);
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const attr = (o) => esc(JSON.stringify(o)).replace(/&quot;/g, '"').replace(/'/g, "&#39;");
const GSAP = "https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js";
const LIBS = ["lib/f1/voice.js", "lib/f1/timing.js", "lib/f1/core.js", "lib/f1/mascot.js", "lib/f1/toon.js", "lib/f1/photo.js", "lib/f1/words.js", "lib/f1/bits.js", "lib/f1/rig.js", "lib/f1/world.js", "lib/f1/cine.js"];
const HEADER = "<!-- GENERATED by scripts/sync.mjs from src/data/rupiah-voice.json: edit the script, not this file. -->";

const changed = [];
const write = (rel, text) => {
  const path = join(root, rel);
  const old = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (old === text) return;
  changed.push(rel);
  if (!checkOnly) writeFileSync(path, text);
};

/* ------------------------------------------------------------------ lib/f1/voice.js */

write(
  "lib/f1/voice.js",
  `// GENERATED by scripts/sync.mjs from src/data/rupiah-voice.json (voiceover/generate.py). Do not edit.\n(globalThis.F1 = globalThis.F1 || {}).VOICE = ${JSON.stringify(voice)};\n`,
);

/* ------------------------------------------------------------------ index.html */

const host = ({ id, src, start, dur, track, z, kind = "graphics", vars }) =>
  `    <div id="${id}" data-composition-id="${id}" data-composition-src="${src}"${vars ? ` data-variable-values='${attr(vars)}'` : ""} data-start="${start}" data-duration="${dur}" data-track-index="${track}" data-track-kind="${kind}" data-width="${W}" data-height="${H}" style="z-index: ${z}"></div>`;

const scenes = [];
const audio = [];
for (const s of segments) {
  if (s.kind === "chapter") {
    scenes.push(host({ id: `chapter-${s.chapterIndex + 1}`, src: "compositions/chapter-card.html", start: sec(s.from), dur: sec(s.duration), track: 1, z: 1, vars: { index: s.chapterIndex + 1, title: s.chapter } }));
  } else {
    const id = s.section.id;
    if (!existsSync(join(root, "compositions", `${id}.html`))) throw new Error(`compositions/${id}.html is missing (every voice section needs a scene file)`);
    scenes.push(host({ id, src: `compositions/${id}.html`, start: sec(s.from), dur: sec(s.duration), track: 1, z: 1 }));
    audio.push(`    <audio id="voice-${id}" src="public/${s.section.audio}" data-start="${sec(s.from)}" data-duration="${Math.floor(Math.min(sec(s.from + s.duration) - sec(s.from), s.section.duration) * 1e4) / 1e4}" data-track-index="10" data-volume="1"></audio>`);
  }
}

write(
  "index.html",
  `<!doctype html>
${HEADER}
<html lang="id">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${W}, height=${H}" />
    <title>Rupiah Tembus Rp18.000: Siapa yang Untung?</title>
    <link rel="stylesheet" href="lib/f1/f1.css" />
    <script src="${GSAP}"></script>
${LIBS.map((l) => `    <script src="${l}"></script>`).join("\n")}
    <style>
      * {
        margin: 0;
        padding: 0;
        box-sizing: border-box;
      }
      html,
      body {
        width: ${W}px;
        height: ${H}px;
        overflow: hidden;
        background: var(--editorial-bg);
      }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="rupiah" data-start="0" data-duration="${sec(total)}" data-fps="${FPS}" data-width="${W}" data-height="${H}">
${host({ id: "background", src: "compositions/background.html", start: 0, dur: sec(total), track: 0, z: 0 })}
${scenes.join("\n")}
${host({ id: "captions", src: "compositions/captions.html", start: 0, dur: sec(total), track: 3, z: 100, kind: "captions" })}
${audio.join("\n")}
    </div>
    <script>
      window.__timelines["rupiah"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`,
);

/* ------------------------------------------------------------------ compositions/captions.html */

const LEAD = 0.05; // seconds a group appears before its first word
const KEEP_GAP = 0.7; // a group stays until the next one if that starts within this many seconds of its end
// the lime keyword of a group: its stat words (numbers), else its last word
const keyWords = (words) => {
  const stats = words.map((w) => F1.isStat(w.word));
  return stats.some(Boolean) ? stats : words.map((_, i) => i === words.length - 1);
};

const capClips = [];
const capData = [];
for (const s of segments.filter((x) => x.kind === "section")) {
  const t0 = s.from / FPS;
  const tEnd = (s.from + s.duration) / FPS;
  const groups = F1.captionGroups(s.section);
  groups.forEach((g, gi) => {
    const id = `cap-${s.section.id}-${gi}`;
    const first = g.words[0].start;
    const lastEnd = g.words[g.words.length - 1].end;
    const next = groups[gi + 1];
    const linger = next && next.words[0].start - lastEnd < KEEP_GAP;
    const start = t0 + first - LEAD;
    const end = Math.min(tEnd, linger ? t0 + next.words[0].start - LEAD : t0 + lastEnd + 0.6);
    const key = keyWords(g.words);
    const words = g.words
      .map((w, wi) => `<span id="${id}-w${wi}"${key[wi] ? ' class="cap-key"' : ""}>${esc(w.word)}</span>${wi < g.words.length - 1 ? " " : ""}`)
      .join("");
    capClips.push(
      `  <div id="${id}" class="clip cap" data-start="${start.toFixed(3)}" data-duration="${(end - start).toFixed(3)}" data-track-index="0"><div class="cap-text" id="${id}-text"><span class="cap-box">${words}</span></div></div>`,
    );
    capData.push({ id, start: +start.toFixed(3), out: linger ? null : +(t0 + lastEnd + 0.35).toFixed(3), words: g.words.map((w, wi) => [+(t0 + w.start).toFixed(3), key[wi] ? 1 : 0, +(t0 + (g.words[wi + 1] ? g.words[wi + 1].start : w.end + 0.15)).toFixed(3)]) });
  });
}

write(
  "compositions/captions.html",
  `${HEADER}
<!-- Karaoke captions, band y 1496..1632 (over the speaker's torso, below the face, clear of the bottom 15% and the platform buttons on the right): up to 6 words in sentence case on a dark box. Words still to come are dimmed; a lime box sits behind the word being spoken; a keyword (a number, else the last word) stays lime once said. -->
<template>
  <link rel="stylesheet" href="lib/f1/f1.css" />
  <style>
    #root {
      position: absolute;
      inset: 0;
      pointer-events: none;
    }
    .cap {
      position: absolute;
      left: 0;
      right: 0;
      top: 1496px;
      height: 136px;
      display: flex;
      align-items: center;
      justify-content: center;
      padding: 0 130px 0 70px;
    }
    .cap-text {
      max-width: 820px;
      font-family: "Montserrat", sans-serif;
      font-weight: 800;
      font-size: 46px;
      line-height: 1.46;
      text-align: center;
    }
    .cap-box {
      padding: 6px 14px;
      border-radius: 12px;
      background: rgba(16, 16, 20, 0.84);
      -webkit-box-decoration-break: clone;
      box-decoration-break: clone;
    }
    .cap-box span {
      padding: 0 6px;
      border-radius: 8px;
      color: rgba(255, 255, 255, 0.62);
    }
  </style>
  <div id="root" data-composition-id="captions" data-width="${W}" data-height="${H}">
${capClips.join("\n")}
  </div>
  <script>
    (() => {
      const GROUPS = ${JSON.stringify(capData)};
      const tl = gsap.timeline({ paused: true });
      for (const g of GROUPS) {
        const text = document.getElementById(g.id + "-text");
        // rises in over 5 frames, out over 0.2 s unless the next caption follows right away
        tl.fromTo(text, { opacity: 0, y: 14 }, { opacity: 1, y: 0, duration: 5 / 30, ease: "power2.out" }, g.start);
        // karaoke: a lime box sits behind the word being spoken; once said a word is white (keyword: lime)
        g.words.forEach(([t, key, next], wi) => {
          const el = document.getElementById(g.id + "-w" + wi);
          tl.set(el, { color: "#111111", backgroundColor: "#c6f432" }, t);
          tl.set(el, { color: key ? "#c6f432" : "#ffffff", backgroundColor: "rgba(198,244,50,0)" }, next);
        });
        if (g.out !== null) {
          tl.to(text, { opacity: 0, duration: 0.2, ease: "none" }, g.out);
          tl.set(text, { opacity: 0, visibility: "hidden" }, g.out + 0.2);
        }
      }
      window.__timelines["captions"] = tl;
    })();
  </script>
</template>
`,
);

/* ------------------------------------------------------------------ SFX clips in scenes */

const sectionIds = new Set(voice.sections.map((s) => s.id));
for (const file of readdirSync(join(root, "compositions"))) {
  const id = file.replace(/\.html$/, "");
  if (!sectionIds.has(id)) continue;
  const rel = `compositions/${file}`;
  const S = F1.section(id);
  const D = F1.sceneFrames(id);
  const src = readFileSync(join(root, rel), "utf8");
  const out = src.replace(/<audio\b[^>]*\bdata-at="([^"]+)"[^>]*>/g, (tag, spec) => {
    const f = Math.max(0, Math.min(D - 1, Math.round(F1.at(S, spec))));
    const t = `${sec(f)}`;
    let next = /\bdata-start="[^"]*"/.test(tag) ? tag.replace(/\bdata-start="[^"]*"/, `data-start="${t}"`) : tag.replace(/<audio\b/, `<audio data-start="${t}"`);
    // SFX times are local to the scene: say so, so the linter never reads them as root-global timestamps.
    if (!/\bdata-hf-media-start-basis=/.test(next)) next = next.replace(/\bdata-start="/, 'data-hf-media-start-basis="local" data-start="');
    return next;
  });
  write(rel, out);
}

/* ------------------------------------------------------------------ report */

const rels = changed.map((c) => relative(root, join(root, c)));
if (checkOnly) {
  if (rels.length) {
    console.error(`sync: out of date: ${rels.join(", ")} (run npm run sync)`);
    process.exit(1);
  }
  console.log("sync: up to date");
} else {
  console.log(rels.length ? `sync: wrote ${rels.join(", ")}` : "sync: up to date");
  console.log(`sync: ${segments.filter((s) => s.kind === "section").length} sections, ${segments.filter((s) => s.kind === "chapter").length} chapter cards, ${sec(total)} s`);
}
